// 反向映射：字符 → 首字母（懒构建，首次调用时初始化）
let charMap: Map<string, string> | null = null

function getCharMap(): Map<string, string> {
  if (charMap) return charMap
  charMap = new Map()
  for (const [initial, chars] of Object.entries(PINYIN_GROUPS)) {
    for (const ch of chars) {
      charMap.set(ch, initial)
    }
  }
  return charMap
}

/**
 * 将字符串转为拼音首字母串
 * - 中文字符：查表得到首字母（未收录返回空字符串）
 * - 非中文字符：保留原样并转小写
 *
 * 例：'创建订单' → 'cjdd'
 *     'API管理' → 'APIgl'
 */
export function toPinyinInitials(str: string): string {
  const map = getCharMap()
  let result = ''
  for (const ch of str) {
    if (/[\u4e00-\u9fff]/.test(ch)) {
      result += map.get(ch) || ''
    } else {
      result += ch.toLowerCase()
    }
  }
  return result
}
